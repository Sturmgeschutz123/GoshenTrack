create or replace function public.place_customer_order(
    p_product_id bigint,
    p_quantity integer,
    p_customer_name text,
    p_contact_number text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_stock integer;
    v_order_id bigint;
begin
    if coalesce(public.current_app_role() <> 'customer', true) then
        raise exception 'Only active customer accounts can place orders';
    end if;
    if p_quantity <= 0 or length(trim(p_customer_name)) = 0 or length(trim(p_contact_number)) = 0 then
        raise exception 'Enter a name, contact number, and valid quantity';
    end if;

    perform 1 from public.products where product_id = p_product_id and active for update;
    if not found then raise exception 'Product is unavailable'; end if;

    select coalesce(sum(case when transaction_type = 'In' then quantity else -quantity end), 0)
           - coalesce((select sum(quantity) from public.sales where product_id = p_product_id), 0)
    into v_stock
    from public.inventory_transactions
    where product_id = p_product_id;
    if p_quantity > v_stock then raise exception 'Not enough stock is available'; end if;

    insert into public.customer_orders
        (customer_id, product_id, customer_name, contact_number, quantity)
    values
        (auth.uid(), p_product_id, trim(p_customer_name), trim(p_contact_number), p_quantity)
    returning order_id into v_order_id;
    return v_order_id;
end;
$$;

create or replace function public.record_inventory_transaction(
    p_product_id bigint,
    p_transaction_type text,
    p_quantity integer,
    p_reason text,
    p_transaction_date date
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_stock integer;
    v_id bigint;
begin
    if coalesce(public.current_app_role() not in ('staff', 'admin'), true) then
        raise exception 'Staff access is required';
    end if;
    if p_transaction_type not in ('In', 'Out', 'Adjust') or p_quantity <= 0 or length(trim(p_reason)) = 0 then
        raise exception 'Enter a valid transaction type, quantity, and reason';
    end if;

    perform 1 from public.products where product_id = p_product_id and active for update;
    if not found then raise exception 'Product is unavailable'; end if;

    if p_transaction_type <> 'In' then
        select coalesce(sum(case when transaction_type = 'In' then quantity else -quantity end), 0)
               - coalesce((select sum(quantity) from public.sales where product_id = p_product_id), 0)
        into v_stock
        from public.inventory_transactions
        where product_id = p_product_id;
        if p_quantity > v_stock then raise exception 'Quantity exceeds current stock'; end if;
    end if;

    insert into public.inventory_transactions
        (product_id, user_id, transaction_type, quantity, reason, transaction_date)
    values
        (p_product_id, auth.uid(), p_transaction_type, p_quantity, trim(p_reason), coalesce(p_transaction_date, current_date))
    returning transaction_id into v_id;
    return v_id;
end;
$$;

