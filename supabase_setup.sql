create or replace function public.review_customer_order(p_order_id bigint, p_confirm boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_order public.customer_orders%rowtype;
    v_stock integer;
    v_price numeric(10, 2);
begin
    if coalesce(public.current_app_role() not in ('staff', 'admin'), true) then
        raise exception 'Staff access is required';
    end if;

    select * into v_order
    from public.customer_orders
    where order_id = p_order_id and archived_at is null
    for update;
    if not found or v_order.status <> 'Pending' then
        raise exception 'This order is no longer pending';
    end if;

    if p_confirm then
        select unit_price into v_price
        from public.products
        where product_id = v_order.product_id and active
        for update;
        if not found then raise exception 'Product is unavailable'; end if;

        select coalesce(sum(case when transaction_type = 'In' then quantity else -quantity end), 0)
               - coalesce((select sum(quantity) from public.sales where product_id = v_order.product_id), 0)
        into v_stock
        from public.inventory_transactions
        where product_id = v_order.product_id;
        if v_order.quantity > v_stock then raise exception 'Not enough stock to confirm this order'; end if;

        insert into public.sales
            (product_id, user_id, order_id, customer_name, customer_contact, quantity, unit_price)
        values
            (v_order.product_id, auth.uid(), v_order.order_id, v_order.customer_name,
             v_order.contact_number, v_order.quantity, v_price);
    end if;

    update public.customer_orders
    set status = case when p_confirm then 'Confirmed' else 'Declined' end,
        reviewed_by = auth.uid(),
        reviewed_at = now()
    where order_id = p_order_id;
end;
$$;

create or replace function public.admin_modify_record(
    p_kind text,
    p_id bigint,
    p_new_quantity integer,
    p_delete boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_product_id bigint;
    v_old_quantity integer;
    v_new_stock integer;
    v_type text;
    v_order_id bigint;
begin
    if coalesce(public.current_app_role() <> 'admin', true) then
        raise exception 'Admin access is required';
    end if;
    if p_delete then
        raise exception 'Archive records first; permanent deletion is available only in the archive';
    end if;
    if not p_delete and (p_new_quantity is null or p_new_quantity <= 0) then
        raise exception 'Quantity must be greater than zero';
    end if;

    if p_kind = 'inventory' then
        select product_id, quantity, transaction_type into v_product_id, v_old_quantity, v_type
        from public.inventory_transactions where transaction_id = p_id and archived_at is null for update;
        if not found then raise exception 'Inventory transaction not found'; end if;

        perform 1 from public.products where product_id = v_product_id for update;
        select coalesce(sum(case when transaction_type = 'In' then quantity else -quantity end), 0)
               - coalesce((select sum(quantity) from public.sales where product_id = v_product_id), 0)
               - case when v_type = 'In' then v_old_quantity else -v_old_quantity end
               + case when p_delete then 0 when v_type = 'In' then p_new_quantity else -p_new_quantity end
        into v_new_stock
        from public.inventory_transactions where product_id = v_product_id;
        if v_new_stock < 0 then raise exception 'Change would make stock negative'; end if;

        if p_delete then
            delete from public.inventory_transactions where transaction_id = p_id;
        else
            update public.inventory_transactions set quantity = p_new_quantity where transaction_id = p_id;
        end if;
    elsif p_kind = 'sale' then
        select product_id, quantity, order_id into v_product_id, v_old_quantity, v_order_id
        from public.sales where sale_id = p_id and archived_at is null for update;
        if not found then raise exception 'Sale record not found'; end if;
        if v_order_id is not null then raise exception 'Sales linked to customer orders cannot be edited here'; end if;

        perform 1 from public.products where product_id = v_product_id for update;
        select coalesce(sum(case when transaction_type = 'In' then quantity else -quantity end), 0)
               - coalesce((select sum(quantity) from public.sales where product_id = v_product_id), 0)
               + v_old_quantity
               - case when p_delete then 0 else p_new_quantity end
        into v_new_stock
        from public.inventory_transactions where product_id = v_product_id;
        if v_new_stock < 0 then raise exception 'Change would make stock negative'; end if;

        if p_delete then
            delete from public.sales where sale_id = p_id;
        else
            update public.sales set quantity = p_new_quantity where sale_id = p_id;
        end if;
    else
        raise exception 'Unsupported record type';
    end if;
end;
$$;

create or replace function public.admin_list_archive()
